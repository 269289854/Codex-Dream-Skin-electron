let activeLocale: SupportedLocale = DEFAULT_LOCALE

export function normalizeLocale(value: unknown): SupportedLocale {
  return value === 'zh-CN' || value === 'en-US' ? value : DEFAULT_LOCALE
}

export function setActiveLocale(locale: SupportedLocale): void {
  activeLocale = locale
}

export function getActiveLocale(): SupportedLocale {
  return activeLocale
}

export function translate(locale: SupportedLocale, source: string, values: TranslationValues = {}): string {
  const template = locale === 'en-US' ? EN_MESSAGES[source] ?? translateEnglishError(source) ?? translateCompound(source) ?? source : source
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match)
}

function translateCompound(source: string): string | null {
  for (const [suffix, translation] of COMPOUND_SUFFIXES) {
    if (!source.endsWith(suffix)) continue
    const subject = source.slice(0, -suffix.length)
    const translated = EN_MESSAGES[subject]
    if (translated) return `${translated}${translation}`
  }
  return null
}

export function t(source: string, values?: TranslationValues): string {
  return translate(activeLocale, source, values)
}

export function translateLocalizedMessage(locale: SupportedLocale, message: LocalizedMessage): string {
  if ('parts' in message) {
    return message.parts.map((part) => translateLocalizedMessage(locale, part)).join(translate(locale, message.separator))
  }
  const values = message.values
    ? Object.fromEntries(Object.entries(message.values).map(([key, value]) => [
        key,
        typeof value === 'object' ? translateLocalizedMessage(locale, value) : value
      ]))
    : undefined
  return translate(locale, message.source, values)
}

export function tm(message: LocalizedMessage | string): string {
  return typeof message === 'string' ? t(message) : translateLocalizedMessage(activeLocale, message)
}
